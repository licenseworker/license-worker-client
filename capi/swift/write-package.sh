#!/usr/bin/env bash
# Writes Package.swift at the repository root, for Swift Package Manager:
#
#   capi/swift/write-package.sh <version> <checksum>     the released XCFramework
#   capi/swift/write-package.sh --local <path-to.xcframework>   a local build, to test
#
# The release workflow runs the first form, commits the file and tags that
# commit, so the tag's Package.swift names the exact zip attached to it.
set -euo pipefail
cd "$(dirname "$0")/../.."

if [[ "${1:-}" == "--local" ]]; then
  binary=".binaryTarget(name: \"LicenseWorker\", path: \"${2:?path to LicenseWorker.xcframework}\")"
else
  version="${1:?version, e.g. 0.2.1}"
  checksum="${2:?checksum from swift package compute-checksum}"
  url="https://github.com/licenseworker/license-worker-client/releases/download/v${version}/LicenseWorker-v${version}.xcframework.zip"
  binary=".binaryTarget(
            name: \"LicenseWorker\",
            url: \"${url}\",
            checksum: \"${checksum}\"
        )"
fi

cat > Package.swift <<SWIFT
// swift-tools-version:5.9
// Generated by capi/swift/write-package.sh; the release workflow keeps it current.
//
// The C interface of license-worker-client as a Swift package: in Xcode,
// File > Add Package Dependencies, this repository's URL, then
// \`import LicenseWorker\`. See capi/README.md.
import PackageDescription

let package = Package(
    name: "LicenseWorker",
    platforms: [.iOS(.v13), .macOS(.v11)],
    products: [
        .library(name: "LicenseWorker", targets: ["LicenseWorker", "LicenseWorkerLinker"]),
    ],
    targets: [
        ${binary},
        .target(
            name: "LicenseWorkerLinker",
            dependencies: ["LicenseWorker"],
            path: "capi/swift/LicenseWorkerLinker",
            linkerSettings: [
                .linkedFramework("Security"),
                .linkedFramework("CoreFoundation"),
                .linkedLibrary("iconv"),
            ]
        ),
    ]
)
SWIFT
echo "wrote Package.swift"
